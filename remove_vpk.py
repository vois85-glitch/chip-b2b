def process_file(filepath):
    """Process a single file, applying all replacements."""
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()
    
    original = content
    
    for pattern, replacement in REPLACEMENTS:
        content = content.replace(pattern, replacement)
    
    # Clean up double spaces and other artifacts
    content = re.sub(r'  +', ' ', content)
    # Clean up trailing spaces before punctuation
    content = content.replace(' .', '.')
    content = content.replace(' ,', ',')
    content = content.replace('  ', ' ')
    
    if content != original:
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(content)
        # Count changes
        changes = sum(1 for a, b in zip(original, content) if a != b)
        return True
    return False

def find_files():
    """Find all .tsx and .ts files in target directories."""
    files = []
    for target_dir in TARGET_DIRS:
        for root, dirs, filenames in os.walk(target_dir):
            for filename in filenames:
                if filename.endswith(('.tsx', '.ts')) and not filename.endswith('.d.ts'):
                    files.append(os.path.join(root, filename))
    return files

def main():
    files = find_files()
    modified = []
    
    for filepath in files:
        if process_file(filepath):
            modified.append(filepath)
            print(f"Modified: {filepath}")
    
    print(f"\nTotal modified: {len(modified)} files")
    
    # Verify no ВПК references remain
    print("\n--- Verification: searching for remaining ВПК references ---")
    vpk_patterns = ['ВПК', 'военно-промышл', 'оборонн', 'военн', 'военной приёмк', 'MIL-Spec', 'MIL-STD']
    for filepath in files:
        with open(filepath, 'r', encoding='utf-8') as f:
            content = f.read()
        for pattern in vpk_patterns:
            if pattern.lower() in content.lower():
                lines = content.split('\n')
                for i, line in enumerate(lines, 1):
                    if pattern.lower() in line.lower():
                        print(f"  REMAINING: {filepath}:{i}: {line.strip()[:120]}")

if __name__ == '__main__':
    main()
