/**
 * Generate enriched SEO content — 2000-3000 chars of unique text.
 * Sections: opening, category context, applications, selection guide,
 * brand context, status, supply terms, ordering info.
 */
export function generateEnrichedSeoContent(component: ComponentData): string {
  const { sku, name, brand, category, status, analogs, description } = component;
  const isEOL = status === 'EOL';

  // 1. Opening — 1-2 sentences
  const opening = `${sku} от ${brand} — ${name.toLowerCase()}. ${description || ''} Компонент относится к категории «${category}» и предназначен для использования в промышленной электронике, измерительных системах и силовой технике.`;

  // 2. Applications — 3-5 scenarios from category
  const apps = APPLICATION_SCENARIOS[category] || [
    'Промышленная автоматика и системы управления',
    'Измерительная техника и лабораторное оборудование',
    'Силовая электроника и источники питания',
    'Потребительская электроника и бытовая техника',
  ];
  const appsText = `Типичные области применения ${sku}: ${apps.slice(0, 4).join('; ')}.`;

  // 3. Selection criteria — engineering guidance
  const criteria = SELECTION_CRITERIA[category] || `При выборе компонента ${sku} обращайте внимание на электрические параметры, корпус, температурный диапазон и доступность. ChipNet поможет подобрать оптимальный вариант и аналоги.`;
  const criteriaText = criteria;

  // 4. Status-specific — EOL or active
  let statusText = '';
  if (isEOL) {
    statusText = `Компонент ${sku} снят с производства (статус EOL). Для проектов, использующих ${sku}, ChipNet предлагает подбор современных аналогов с pin-to-pin или функциональной совместимостью${analogs && analogs.length > 0 ? `. Рекомендуемые замены: ${analogs.slice(0, 5).join(', ')}` : ''}. Инженерная поддержка миграции включает анализ схемы, подбор кросс-референса, поставку пилотных образцов для тестирования и верификацию на стенде.`;
  } else {
    statusText = `Компонент ${sku} находится в производстве и доступен для поставки. Минимальная партия — от 1 шт., срок поставки 5-30 рабочих дней в зависимости от наличия на складе и канала поставки. Для серийных проектов предлагаем долгосрочные контракты с резервированием складских позиций на 6-12 месяцев.`;
  }

  // 5. Supply & quality
  const supplyText = `Каждая партия ${sku} проходит входной контроль в аккредитованной лаборатории СВП (сертификат РОСС RU.0001.21АЮ02): визуальный осмотр под микроскопом ×40, рентгеновский контроль wire-bond и кристалла, электрические тесты ключевых параметров по даташиту, декэпсуляция 1% выборки. По результатам контроля выдаётся протокол с фотографиями и измерениями.`;

  // 6. Ordering & delivery
  const orderingText = `Для заказа ${sku} отправьте заявку через форму BOM на сайте, по email info@chip-net.ru или телефону +7-910-321-91-91. Менеджер подготовит коммерческое предложение в течение 1-2 часов. Доставка по России — СДЭК, DPD, от 6 рабочих дней. Доставка в Казахстан и Беларусь — по ЕАЭС. Безналичный расчёт с НДС, отсрочка платежа до 30 дней для постоянных клиентов.`;

  // Combine — ~2000-3000 chars
  return `${opening} ${appsText} ${criteriaText} ${statusText} ${supplyText} ${orderingText}`;
}

